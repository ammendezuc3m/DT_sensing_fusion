#!/usr/bin/env python3
"""
Online passive 5G SSB sensing with the Fisher + logistic-regression model.

Pipeline:
    USRP B210
      -> 20 ms IQ capture
      -> optional CFO warmup/correction
      -> PSS/NID2/timing
      -> OFDM demodulation
      -> rxGridSSB = 240 x 4
      -> radio check (NID2 and i_bar_SSB must match the model)
      -> channel estimate H + Fisher features + PyTorch linear model
      -> label -> objects with coordinates (config/sensing_label_map.json)
      -> Sensing API report (POST /sensing/v1/reports, CAPIF-discoverable)
      -> local latest-state JSON + CSV log (+ optional Mitsuba XML)

The model is produced offline by src/python/run_ssb_sensing_analysis.py.
Use --dsp-only to validate the radio chain before a model exists.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
import time
from pathlib import Path

import numpy as np

THIS_DIR = Path(__file__).resolve().parent
for path in (THIS_DIR, THIS_DIR.parent):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

from cfo_utils import apply_frequency_correction  # noqa: E402
from capture_online_rxgridssb_dataset_cfo import estimate_cfo_warmup  # noqa: E402
from profile_online_datassb_pipeline import (  # noqa: E402
    capture_one_block,
    configure_usrp,
    extract_rxgrid_from_waveform,
    make_rx_streamer,
)
from ssb_fisher_torch_inference import SSBFisherTorchModel  # noqa: E402
from sensing_api.label_map import LabelMap  # noqa: E402
from sensing_api.mitsuba import HumanProxyGeometry, HumanRadioMaterial, make_mitsuba_scene_xml  # noqa: E402
from sensing_api.producer import ReportPublisher, build_report  # noqa: E402
from sensing_api.schemas import utc_now_iso  # noqa: E402

SCHEMA_VERSION = "python_5g_ssb_online_v2"

CSV_FIELDS = [
    "iteration", "timestamp_utc", "valid", "label", "confidence", "prob_empty", "n_detections",
    "rx_mean_abs", "pss_metric", "nid2", "detected_pci", "detected_ibar", "cfo_hz",
    "capture_time_ms", "pss_time_ms", "ofdm_time_ms", "dsp_time_ms", "inference_time_ms", "loop_time_ms",
    "api_sent", "api_failed", "error",
]


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)

    # USRP/capture.
    p.add_argument("--serial", default="34B73C3")
    p.add_argument("--freq", type=float, default=3541.44e6)
    p.add_argument("--rate", type=float, default=15.36e6)
    p.add_argument("--gain", type=float, default=60.0)
    p.add_argument("--duration-ms", type=float, default=20.0)
    p.add_argument("--channel", type=int, default=0)
    p.add_argument("--antenna", default="")
    p.add_argument("--settle-sec", type=float, default=0.5)

    # DSP.
    p.add_argument("--nfft", type=int, default=512)
    p.add_argument("--demod-rb", type=int, default=30)
    p.add_argument("--nrb-ssb", type=int, default=20)
    p.add_argument("--num-symbols", type=int, default=6)
    p.add_argument("--force-nid2", type=int, default=0, choices=[0, 1, 2])
    p.add_argument("--min-pss-metric", type=float, default=0.50)

    # CFO.
    p.add_argument("--enable-cfo-correction", action="store_true")
    p.add_argument("--manual-cfo-hz", type=float, default=None)
    p.add_argument("--cfo-warmup-iters", type=int, default=30)
    p.add_argument("--cfo-correction-sign", type=float, default=-1.0)
    p.add_argument("--max-cfo-abs-hz", type=float, default=30000.0)

    # Online loop.
    p.add_argument("--num-iters", type=int, default=0, help="0 means run forever.")
    p.add_argument("--warmup-iters", type=int, default=5, help="Captures discarded before the loop starts.")
    p.add_argument("--progress-every", type=int, default=1)

    # Model.
    p.add_argument("--fisher-model", default="results/ssb_sensing_analysis/model_fisher_logreg.pt",
                   help="model_fisher_logreg.pt generated by run_ssb_sensing_analysis.py.")
    p.add_argument("--torch-device", default="cpu")
    p.add_argument("--fisher-pci", type=int, default=None, help="Override the checkpoint PCI.")
    p.add_argument("--fisher-ibar", type=int, default=None, help="Override the checkpoint i_bar_SSB.")
    p.add_argument("--dsp-only", action="store_true",
                   help="No model: validate capture/DSP and publish valid/invalid status only.")

    # Label -> coordinates.
    p.add_argument("--label-map", default="config/sensing_label_map.json",
                   help="JSON mapping each model label to objects and coordinates.")

    # Sensing API.
    p.add_argument("--sensor-id", default="5g-ssb-rx-01", help="Unique id of this receiver in the Sensing API.")
    p.add_argument("--sensing-api-url", default="", help="Sensing API base URL, e.g. http://host:8090")
    p.add_argument("--capif-url", default="", help="Discover the Sensing API through this CAPIF base URL.")
    p.add_argument("--api-token", default=os.environ.get("SENSING_API_PRODUCER_TOKEN", ""),
                   help="Producer bearer token (default: $SENSING_API_PRODUCER_TOKEN).")
    p.add_argument("--api-timeout-sec", type=float, default=2.0)
    p.add_argument("--publish-every", type=int, default=1, help="Publish one report every N iterations.")
    p.add_argument("--disable-api", action="store_true", help="Run without publishing to the Sensing API.")

    # Local outputs.
    p.add_argument("--local-json", default="results/online/live_inference_state_5G.json")
    p.add_argument("--json-every", type=int, default=1)
    p.add_argument("--log-csv", default="results/online/python_5g_online_inference_log.csv")

    # Optional local Mitsuba/Sionna XML.
    p.add_argument("--enable-mitsuba-export", action="store_true",
                   help="Also write the current detections as a local Mitsuba XML scene.")
    p.add_argument("--mitsuba-output", default="",
                   help="Mitsuba XML path. Default: live_person_sionna_scene.xml next to --local-json.")
    p.add_argument("--mitsuba-every", type=int, default=1)
    p.add_argument("--mitsuba-body-radius-x-m", type=float, default=0.28)
    p.add_argument("--mitsuba-body-radius-y-m", type=float, default=0.18)
    p.add_argument("--mitsuba-body-half-height-m", type=float, default=0.62)
    p.add_argument("--mitsuba-body-center-z-m", type=float, default=0.92)
    p.add_argument("--mitsuba-head-radius-m", type=float, default=0.12)
    p.add_argument("--mitsuba-head-center-z-m", type=float, default=1.62)
    p.add_argument("--mitsuba-human-material-name", default="human_body_standard")
    p.add_argument("--mitsuba-human-epsilon-r", type=float, default=38.0)
    p.add_argument("--mitsuba-human-mu-r", type=float, default=1.0)
    p.add_argument("--mitsuba-human-conductivity-s-per-m", type=float, default=1.46)

    args = p.parse_args()
    for name in ("publish_every", "json_every", "mitsuba_every"):
        if getattr(args, name) < 1:
            p.error(f"--{name.replace('_', '-')} must be >= 1")
    if not args.disable_api and not (args.sensing_api_url or args.capif_url):
        p.error("Give --sensing-api-url or --capif-url, or use --disable-api.")
    return args


def atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def resolve_log_csv(path: Path) -> Path:
    """Append to ``path`` only if it has the current columns; otherwise start a new file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.stat().st_size == 0:
        return path
    with path.open(newline="", encoding="utf-8") as f:
        header = next(csv.reader(f), [])
    if header == CSV_FIELDS:
        return path
    new_path = path.with_name(f"{path.stem}_{time.strftime('%Y%m%d_%H%M%S')}{path.suffix}")
    print(f"[WARN] {path} has different columns (older version); logging to {new_path}")
    return new_path


def sensor_description(args: argparse.Namespace, model: SSBFisherTorchModel | None) -> dict:
    return {
        "sensor_id": args.sensor_id,
        "sensor_type": "5g_ssb",
        "technology": "5G-NR",
        "method": "passive_ssb_fingerprinting",
        "model_name": model.model_name if model else None,
        "model_version": Path(args.fisher_model).name if model else None,
        "metadata": {
            "center_frequency_hz": float(args.freq),
            "sample_rate_sps": float(args.rate),
            **({"pci": model.pci, "ibar": model.ibar} if model else {}),
        },
    }


def process_iteration(
    rx_streamer, samples_per_block: int, max_samps: int, actual_rate: float,
    cfo_hz: float, apply_cfo: bool, args: argparse.Namespace, model: SSBFisherTorchModel | None,
) -> dict:
    """Capture and process one block. Returns a result dict; never raises."""
    result = {"valid": False, "prediction": None, "error": "", "timing": {}, "dsp": {}, "radio_check": None,
              "rx_mean_abs": float("nan"), "inference_time_ms": float("nan"), "capture_time_ms": float("nan")}
    try:
        t0 = time.perf_counter()
        waveform = capture_one_block(rx_streamer=rx_streamer, total_samples=samples_per_block, max_samps=max_samps)
        result["capture_time_ms"] = 1000.0 * (time.perf_counter() - t0)

        if apply_cfo:
            waveform = apply_frequency_correction(
                waveform=waveform, cfo_hz=cfo_hz, sample_rate=actual_rate, sign=args.cfo_correction_sign
            )

        _data_ssb, rx_grid, timing_info, timing_breakdown = extract_rxgrid_from_waveform(waveform=waveform, args=args)
        result["timing"] = timing_breakdown or {}
        result["dsp"] = {
            "nid2": int(timing_info.get("nid2", -1)),
            "pss_metric": float(timing_info.get("metric", 0.0)),
            "timing_offset_samples": int(timing_info.get("timing_offset_samples", -1)),
            "n_symbols_extracted": int(timing_info.get("n_symbols_extracted", 0)),
        }
        if rx_grid is not None and np.size(rx_grid):
            result["rx_mean_abs"] = float(np.mean(np.abs(rx_grid)))

        if result["dsp"]["pss_metric"] < args.min_pss_metric:
            result["error"] = f"pss_metric_below_threshold ({result['dsp']['pss_metric']:.3f})"
            return result
        if result["dsp"]["n_symbols_extracted"] != args.num_symbols or rx_grid is None or rx_grid.shape != (240, 4):
            result["error"] = "incomplete_ssb_grid"
            return result

        if model is None:
            result["valid"] = True
            return result

        t1 = time.perf_counter()
        check = model.check_radio(rx_grid, nid2=result["dsp"]["nid2"])
        result["radio_check"] = check.as_dict()
        if not check.ok:
            result["error"] = check.reason
            return result
        result["prediction"] = model.predict_proba(rx_grid)
        result["inference_time_ms"] = 1000.0 * (time.perf_counter() - t1)
        result["valid"] = True
    except Exception as exc:  # keep the online loop alive on capture/DSP failures
        result["error"] = f"{type(exc).__name__}: {exc}"
    return result


def make_local_state(iteration: int, timestamp: str, result: dict, report: dict, loop_time_ms: float) -> dict:
    """Latest-state JSON written locally (same content as the API report + diagnostics)."""
    timing = result["timing"]
    return {
        "schema_version": SCHEMA_VERSION,
        "timestamp_utc": timestamp,
        "iteration": iteration,
        "valid": report["valid"],
        "error": result["error"],
        "sensor": report["sensor"],
        "label": report["label"],
        "confidence": report["confidence"],
        "probabilities": report["probabilities"],
        "detections": report["detections"],
        "dsp": result["dsp"],
        "radio_check": result["radio_check"],
        "timing_ms": {
            "capture": result["capture_time_ms"],
            "pss": float(timing.get("pss_time_ms", float("nan"))),
            "ofdm": float(timing.get("ofdm_time_ms", float("nan"))),
            "dsp_total": float(timing.get("total_dsp_time_ms", float("nan"))),
            "inference": result["inference_time_ms"],
            "loop_total": loop_time_ms,
        },
    }


def main() -> None:
    args = parse_args()

    model = None
    if not args.dsp_only:
        model = SSBFisherTorchModel(args.fisher_model, device=args.torch_device, pci=args.fisher_pci, ibar=args.fisher_ibar)
    label_map = LabelMap.load(args.label_map)
    if model is not None:
        label_map.require_labels(model.classes)  # fail now instead of publishing made-up coordinates
    empty_labels = label_map.empty_labels()

    local_json = Path(args.local_json)
    log_csv = Path(args.log_csv)
    mitsuba_xml = Path(args.mitsuba_output) if args.mitsuba_output else local_json.with_name("live_person_sionna_scene.xml")
    geometry = HumanProxyGeometry(
        body_radius_x_m=args.mitsuba_body_radius_x_m, body_radius_y_m=args.mitsuba_body_radius_y_m,
        body_half_height_m=args.mitsuba_body_half_height_m, body_center_z_m=args.mitsuba_body_center_z_m,
        head_radius_m=args.mitsuba_head_radius_m, head_center_z_m=args.mitsuba_head_center_z_m,
    )
    material = HumanRadioMaterial(
        name=args.mitsuba_human_material_name, relative_permittivity=args.mitsuba_human_epsilon_r,
        relative_permeability=args.mitsuba_human_mu_r,
        conductivity_s_per_m=args.mitsuba_human_conductivity_s_per_m,
    )

    publisher = None
    if not args.disable_api:
        publisher = ReportPublisher(
            base_url=args.sensing_api_url or None, capif_url=args.capif_url or None,
            token=args.api_token or None, timeout_s=args.api_timeout_sec, app_name=args.sensor_id,
        )
    sensor = sensor_description(args, model)

    print("=== Online 5G SSB sensing ===")
    if model:
        print(f"Fisher model:       {args.fisher_model}")
        print(f"classes:            {model.classes}")
        print(f"radio config:       PCI={model.pci} i_bar={model.ibar} (NID2 must be {model.pci % 3})")
    else:
        print("model:              none (--dsp-only)")
    print(f"label map:          {args.label_map} (frame={label_map.frame_id})")
    print(f"sensor id:          {args.sensor_id}")
    print(f"Sensing API:        {'disabled' if publisher is None else (args.sensing_api_url or 'CAPIF ' + args.capif_url)}")
    print(f"local JSON:         {local_json}")
    print(f"mitsuba export:     {mitsuba_xml if args.enable_mitsuba_export else 'disabled'}")
    if model and args.force_nid2 != model.pci % 3:
        print(f"[WARN] --force-nid2 {args.force_nid2} differs from the model NID2 {model.pci % 3}: "
              "every grid will be rejected.")

    usrp = configure_usrp(args)
    actual_rate = float(usrp.get_rx_rate(args.channel))
    samples_per_block = int(round(actual_rate * args.duration_ms * 1e-3))
    rx_streamer = make_rx_streamer(usrp, args.channel)
    max_samps = rx_streamer.get_max_num_samps()

    apply_cfo = bool(args.enable_cfo_correction or args.manual_cfo_hz is not None)
    if args.manual_cfo_hz is not None:
        cfo_hz = float(args.manual_cfo_hz)
        print(f"\nUsing manual CFO: {cfo_hz:.3f} Hz")
    elif args.enable_cfo_correction:
        try:
            cfo_hz, _ = estimate_cfo_warmup(
                rx_streamer=rx_streamer, samples_per_block=samples_per_block, max_samps=max_samps,
                sample_rate=actual_rate, args=args,
            )
        except RuntimeError as exc:
            raise SystemExit(
                f"\n[ERROR] CFO warmup failed ({exc}): no SSB was detected at "
                f"{args.freq / 1e6:.3f} MHz with NID2={args.force_nid2} (PSS metric below "
                f"{args.min_pss_metric}). Check that the gNB is transmitting, the frequency, "
                "--force-nid2, the antenna port and the gain. "
                "scan_5g_ssb_auto.py finds the SSBs on air."
            ) from None
    else:
        cfo_hz = 0.0
        print("\nCFO correction disabled.")

    for _ in range(max(0, args.warmup_iters)):
        capture_one_block(rx_streamer=rx_streamer, total_samples=samples_per_block, max_samps=max_samps)

    print("\n=== Online loop ===")
    print(f"samples/block:      {samples_per_block}")
    print(f"CFO applied:        {cfo_hz:.3f} Hz")
    print(f"num iters:          {'forever' if args.num_iters == 0 else args.num_iters}")

    log_csv = resolve_log_csv(log_csv)
    write_header = not log_csv.exists()
    i = 0
    try:
        with log_csv.open("a", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=CSV_FIELDS)
            if write_header:
                writer.writeheader()

            while args.num_iters == 0 or i < args.num_iters:
                loop_t0 = time.perf_counter()
                result = process_iteration(
                    rx_streamer, samples_per_block, max_samps, actual_rate, cfo_hz, apply_cfo, args, model
                )
                timestamp = utc_now_iso()
                report = build_report(
                    sensor=sensor, sequence=i, valid=result["valid"], prediction=result["prediction"],
                    label_map=label_map, invalid_reason=result["error"] or None, timestamp=timestamp,
                    extra={"dsp": result["dsp"], "cfo_hz": cfo_hz},
                )
                if publisher is not None and i % args.publish_every == 0:
                    publisher.submit(report)

                loop_time_ms = 1000.0 * (time.perf_counter() - loop_t0)
                if i % args.json_every == 0:
                    state = make_local_state(i, timestamp, result, report, loop_time_ms)
                    atomic_write_text(local_json, json.dumps(state, indent=2))
                if args.enable_mitsuba_export and i % args.mitsuba_every == 0:
                    atomic_write_text(mitsuba_xml, make_mitsuba_scene_xml(
                        report["detections"], timestamp_utc=timestamp, frequency_hz=args.freq,
                        geometry=geometry, material=material,
                    ))

                probs = report["probabilities"]
                timing = result["timing"]
                row = {
                    "iteration": i,
                    "timestamp_utc": timestamp,
                    "valid": int(report["valid"]),
                    "label": report["label"] or ("NONE" if report["valid"] else "INVALID"),
                    "confidence": report["confidence"] if report["confidence"] is not None else np.nan,
                    "prob_empty": sum(v for k, v in probs.items() if k in empty_labels) if probs else np.nan,
                    "n_detections": len(report["detections"]),
                    "rx_mean_abs": result["rx_mean_abs"],
                    "pss_metric": result["dsp"].get("pss_metric", np.nan),
                    "nid2": result["dsp"].get("nid2", -1),
                    "detected_pci": (result["radio_check"] or {}).get("detected_pci", -1),
                    "detected_ibar": (result["radio_check"] or {}).get("detected_ibar", -1),
                    "cfo_hz": cfo_hz,
                    "capture_time_ms": result["capture_time_ms"],
                    "pss_time_ms": timing.get("pss_time_ms", np.nan),
                    "ofdm_time_ms": timing.get("ofdm_time_ms", np.nan),
                    "dsp_time_ms": timing.get("total_dsp_time_ms", np.nan),
                    "inference_time_ms": result["inference_time_ms"],
                    "loop_time_ms": loop_time_ms,
                    "api_sent": publisher.stats.sent if publisher else 0,
                    "api_failed": publisher.stats.failed if publisher else 0,
                    "error": result["error"],
                }
                writer.writerow(row)
                f.flush()

                if args.progress_every > 0 and i % args.progress_every == 0:
                    conf = f"{row['confidence']:.3f}" if report["confidence"] is not None else "-"
                    api = f"api={publisher.stats.sent}/{publisher.stats.failed}" if publisher else "api=off"
                    print(
                        f"[{i:06d}] valid={row['valid']} label={row['label']} conf={conf} "
                        f"objs={row['n_detections']} rx_mean={row['rx_mean_abs']:.3f} "
                        f"pss={row['pss_metric']:.3f} loop={loop_time_ms:.2f} ms {api} err={result['error']}"
                    )
                i += 1
    except KeyboardInterrupt:
        print("\nInterrupted by user.")
    finally:
        if publisher is not None:
            publisher.close()
            s = publisher.stats
            print(f"Sensing API: sent={s.sent} failed={s.failed} dropped={s.dropped} last_error={s.last_error!r}")


if __name__ == "__main__":
    main()
